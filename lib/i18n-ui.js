    let appLanguage = (() => { try { const stored = localStorage.getItem(I18N_KEY); if (stored === 'en' || stored === 'zh-Hant') return stored; const old = localStorage.getItem(GUIDE_LANGUAGE_KEY_OLD); if (old === 'zh-Hant') return 'zh-Hant'; } catch {} return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh-Hant' : 'en'; })();
    function t(key, vars) {
      const value = i18nDict[appLanguage]?.[key] ?? i18nDict.en[key] ?? key;
      return vars ? value.replace(/\{(\w+)\}/g, (match, name) => vars[name] ?? match) : value;
    }
    function setAppLanguage(lang) {
      if (lang !== 'en' && lang !== 'zh-Hant') return;
      appLanguage = lang;
      try { localStorage.setItem(I18N_KEY, lang); } catch {}
      applyAppLanguage(true);
    }
    function applyAppLanguage(full) {
      document.documentElement.lang = appLanguage === 'zh-Hant' ? 'zh-Hant' : 'en';
      document.title = t('page.title');
      document.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
      document.querySelectorAll('[data-i18n-aria]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nAria)); });
      document.querySelectorAll('[data-i18n-title]').forEach(node => { node.title = t(node.dataset.i18nTitle); });
      document.querySelectorAll('[data-i18n-placeholder]').forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
      document.querySelectorAll('[data-i18n-alt]').forEach(node => { node.alt = t(node.dataset.i18nAlt); });
      const en = document.getElementById('lang-en'), zh = document.getElementById('lang-zh');
      if (en) en.setAttribute('aria-pressed', String(appLanguage === 'en'));
      if (zh) zh.setAttribute('aria-pressed', String(appLanguage === 'zh-Hant'));
      document.querySelectorAll('.plan-switch').forEach(control => {
        const state = control.querySelector('.switch-state');
        if (state) state.textContent = control.getAttribute('aria-checked') === 'true' ? t('switch.on') : t('switch.off');
      });
      if (!full) return;
      try { if (typeof guideLanguage !== 'undefined') guideLanguage = appLanguage; } catch {}
      try { if (typeof updateInputGuide === 'function') updateInputGuide(); } catch {}
      try { if (typeof updateDockState === 'function') updateDockState(); } catch {}
      try { if (typeof updateGuidance === 'function') updateGuidance(); } catch {}
      try { if (typeof render === 'function') render(false); } catch {}
      try { if (typeof routing !== 'undefined' && routing.result && typeof showRoutes === 'function') showRoutes(); } catch {}
      try { if (typeof routing !== 'undefined' && routing.selected && typeof routeDetails === 'function') routeDetails(); } catch {}
      try { if (typeof setMapMarkersVisible === 'function' && typeof mapMarkersVisible !== 'undefined') setMapMarkersVisible(mapMarkersVisible); } catch {}
      try { if (typeof analyticsStatus === 'function') analyticsStatus(); } catch {}
    }
    document.getElementById('lang-en')?.addEventListener('click', () => setAppLanguage('en'));
    document.getElementById('lang-zh')?.addEventListener('click', () => setAppLanguage('zh-Hant'));
